"""evidence_relations/synthetic: a two-signal extension of the Gao-style AR(1) replication (data/datasets/
ar1_forecasting in 1_overreaction), ported faithfully from 1_overreaction/repro/
evidence_relations/{generate,prompts,build}.py (this file) and bayes.py (its own submodule, evidence_relations/
bayes.py). Full derivation, every design decision and all build-time self-checks: evidence_relations/synthetic/
DESIGN.md, ported from the same source project's DESIGN.md.

At every round, alongside the usual 40-point AR(1) history, the model is given two noisy signals about the
upcoming change, Signal A and Signal B, each labelled with its own stated noise level (tau). The signals' true
correlation c (how redundant they are) is known to the generator but never told to the model. Three variants:
`base` (the c x tau x rho redundancy-discount factorial), `stale` (a signal that verbatim-repeats an earlier
round, which must get zero weight), `contradiction` (the two signals forced to disagree, with different stated
noise levels, so the lower-noise one should win). 30 conditions, 153,600 rows (train 76,800 / val 38,400 /
test 38,400). Every row's `bayes_optimal_delta1` / `bayes_optimal_posterior_var` is the exact closed-form
answer (bayes.py), evaluated at the row's own true generative parameters -- not estimated, not approximated.

    finagent evidence-synthetic                  regenerate {train,val,test}.jsonl.xz + MANIFEST.sha256 under
                                                   data/evidence_relations/synthetic/ (deterministic; source of
                                                   truth, see "Source of truth" below)
    finagent evidence-synthetic --out DIR         write elsewhere instead
    finagent evidence-synthetic --check           regenerate in memory (no files written) and compare, byte for
                                                   byte, against the shipped data/evidence_relations/synthetic/*.xz
                                                   (decompressed) and its MANIFEST.sha256 / build_summary.json

Source of truth. The generator (this file, with bayes.py and a fixed BASE_SEED) is the source of truth: it is
what `finagent evidence-synthetic --check` recomputes and what every number in DESIGN.md and README.md is
reported from. The shipped `data/evidence_relations/synthetic/{train,val,test}.jsonl.xz` are a compressed cache of
exactly that generator's output, kept so the data can be inspected or used without regenerating (the quick
start in README.md: `xz -d -k -c train.jsonl.xz | head`); `--check` decompresses them and asserts they still
equal the freshly regenerated bytes, so the two are proved to agree (not merely assumed to), and the shipped
archives can be re-derived from the code at any time.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import lzma
import platform
import re
from pathlib import Path

import numpy as np

from finagent.evidence_relations import ROOT as EVIDENCE_ROOT
from finagent.evidence_relations import bayes as B

# ================================================================================================== generate (AR(1) realizations)
RHOS = (0.0, 0.4, 0.8)
SIGMA = 20.0
HISTORY_LEN = 40
N_ROUNDS = 40
SERIES_LEN = HISTORY_LEN + N_ROUNDS  # 80: indices 0..79, round 40 needs index 79

# Two tau settings (signal informative / signal noisy), as multiples of sigma.
TAU_MULT = {"informative": 0.5, "noisy": 2.0}
TAU_SETTINGS = {k: v * SIGMA for k, v in TAU_MULT.items()}  # informative=10.0, noisy=40.0

# Redundancy sweep for the base variant.
C_VALUES = (0.0, 0.5, 0.95)

# Asymmetric-precision regimes for the contradiction variant (tau1, tau2), reusing the same two tau magnitudes
# but assigned unevenly between Signal A and Signal B, in both directions.
CONTRA_REGIMES = {
    "A_informative_B_noisy": (TAU_SETTINGS["informative"], TAU_SETTINGS["noisy"]),
    "A_noisy_B_informative": (TAU_SETTINGS["noisy"], TAU_SETTINGS["informative"]),
}

BASE_SEED = 20261020  # build date; own seed tree (a separate SeedSequence call from every other finagent module)
SPLIT_INDEX = {"train": 0, "val": 1, "test": 2}
N_REALIZATIONS = {"train": 64, "val": 32, "test": 32}
GROUP_INDEX = {"base": 0, "stale": 1, "contradiction": 2}
PURPOSE_INDEX = {"series": 0, "noise": 1, "stale_flag": 2}

SPLITS = ("train", "val", "test")
P_STALE = 0.30  # probability a round r>=2 in the stale variant repeats the previous round's s2
WEIGHT_PREC = 4  # decimals for weight_s1/weight_s2 (dimensionless, 0..1); everything else uses round2 (2 decimals)


def round2(a):
    """Round to 2 decimals; adding 0.0 turns -0.0 into +0.0 so it never prints as '-0.0'."""
    return np.round(np.asarray(a, dtype=np.float64), 2) + 0.0


def rng_for(purpose: str, group: str, split: str, rho_idx: int, c_idx: int, tau_idx: int) -> np.random.Generator:
    """One independent PCG64 stream per (purpose, variant-group, split, rho, c, tau), DESIGN.md S2: every
    condition draws its own independent realizations, never common shocks reused across conditions."""
    ss = np.random.SeedSequence(BASE_SEED,
                                 spawn_key=(PURPOSE_INDEX[purpose], GROUP_INDEX[group], SPLIT_INDEX[split],
                                            rho_idx, c_idx, tau_idx))
    return np.random.Generator(np.random.PCG64(ss))


def initial_sd(rho: float, sigma: float = SIGMA) -> float:
    return sigma / np.sqrt(1.0 - rho ** 2) if rho < 1.0 else sigma


def simulate_series(rho: float, n_real: int, rng: np.random.Generator, sigma: float = SIGMA,
                     length: int = SERIES_LEN) -> np.ndarray:
    """(n_real, length) float64 array; stationary start (DESIGN.md S1, every rho here is < 1). Row i uses draws
    i*length..(i+1)*length-1 of the stream, so the first k realizations do not change if n_real is increased."""
    z = rng.standard_normal((n_real, length))
    x = np.empty((n_real, length), dtype=np.float64)
    x[:, 0] = initial_sd(rho, sigma) * z[:, 0]
    for k in range(1, length):
        x[:, k] = rho * x[:, k - 1] + sigma * z[:, k]
    return x


def round_index(round_: int) -> int:
    """Series index of x_t in round `round_` (1-based)."""
    return HISTORY_LEN - 2 + round_  # round 1 -> 39, round 40 -> 78


# ================================================================================================== prompts
INTRO_PAIRS = (
    "Below are the 40 most recent data points of a time series, ordered from oldest to newest. "
    "Each data point is written as a pair [value, change], where change is the value minus the "
    "previous value. The first data point has no previous value in the list, so its change is None."
)
DATA_PREFIX = "Past 40 pts: "

SIGNAL_INTRO_A_FIRST = (
    "You also have two noisy signals about the change from the last value to the next value "
    "(one step ahead). Neither signal is the change itself; each signal's stated noise level is "
    "your only information about how reliable it is."
)
SIGNAL_INTRO_B_FIRST = (
    "Two noisy signals about the change from the last value to the next value (one step ahead) "
    "are also available below. Each is labeled with its own stated noise level, which is your "
    "only indication of its reliability."
)
PREV_SIGNAL_B_NOTE = "In the previous round, Signal B's value was {prev}."
TASK_A_FIRST = (
    "Predict Δ1, your forecast of the change from the last value in the list to the next "
    "value (one step ahead), using the history and both signals above."
)
TASK_B_FIRST = (
    "Forecast Δ1 — the one-step-ahead change from the last listed value — using "
    "the history and both signals above."
)
OUTPUT_INSTRUCTION = (
    "First, in one short sentence, say which signal or signals (Signal A, Signal B, both, or "
    "neither) you weight more heavily and why.\n"
    "Then, on a new line, answer with only a JSON object in exactly this format and no other "
    'text after it: {"delta1": <number>}'
)


def fmt_num(v: float) -> str:
    """Python repr of the 2-decimal value (13.9, -20.85, 0.0)."""
    return repr(float(round2(v)))


def pairs_text(history) -> str:
    h = round2(history)
    items = [f"[{fmt_num(h[0])}, None]"]
    for k in range(1, len(h)):
        items.append(f"[{fmt_num(h[k])}, {fmt_num(h[k] - h[k - 1])}]")
    return "[" + ", ".join(items) + "]"


def signal_line(name: str, value: float, tau: float) -> str:
    return f"{name}: {fmt_num(value)} (noise level: {fmt_num(tau)})"


def build_variants(history, s1: float, s2: float, tau1: float, tau2: float, prev_s2=None) -> dict:
    """{base, position_swapped}: identical statistical content (same Signal A/B values and noise levels),
    differing only in which signal is introduced first and how the sentences around it read (DESIGN.md S6)."""
    data_line = DATA_PREFIX + pairs_text(history)
    line_a = signal_line("Signal A", s1, tau1)
    line_b = signal_line("Signal B", s2, tau2)
    prev_line = None if prev_s2 is None else PREV_SIGNAL_B_NOTE.format(prev=fmt_num(prev_s2))

    base_signal_block = [line_a, line_b] + ([prev_line] if prev_line else [])
    swapped_signal_block = [line_b] + ([prev_line] if prev_line else []) + [line_a]

    base = "\n\n".join([INTRO_PAIRS, data_line, SIGNAL_INTRO_A_FIRST, "\n".join(base_signal_block),
                        TASK_A_FIRST, OUTPUT_INSTRUCTION])
    position_swapped = "\n\n".join([INTRO_PAIRS, data_line, SIGNAL_INTRO_B_FIRST, "\n".join(swapped_signal_block),
                                    TASK_B_FIRST, OUTPUT_INSTRUCTION])
    return {"base": base, "position_swapped": position_swapped}


def reasoning_sentence(tau1: float, tau2: float, stale_round: bool) -> str:
    """Canonical, formula-derived reasoning sentence used in sft_target: a fixed function of the condition's
    known parameters, never freeform or random text."""
    if stale_round:
        return ("Signal B repeats the previous round with no new information, so it gets zero additional "
                "weight; only Signal A is used.")
    if abs(tau1 - tau2) < 1e-9:
        return "Signal A and Signal B have the same stated noise level, so the Bayes-optimal forecast weights them equally."
    lower = "Signal A" if tau1 < tau2 else "Signal B"
    higher = "Signal B" if tau1 < tau2 else "Signal A"
    return f"{lower} has the lower noise level than {higher}, so it is weighted more heavily."


def sft_target_text(tau1: float, tau2: float, stale_round: bool, delta1: float) -> str:
    sentence = reasoning_sentence(tau1, tau2, stale_round)
    return sentence + '\n{"delta1": %.2f}' % float(round2(delta1))


# ================================================================================================== build
def build_condition(split: str, variant: str, rho: float, rho_idx: int, c: float, c_idx: int, tau1: float,
                     tau2: float, tau_idx: int, tau_setting: str, seen: set) -> list[dict]:
    n_real = N_REALIZATIONS[split]
    rng_series = rng_for("series", variant, split, rho_idx, c_idx, tau_idx)
    full = simulate_series(rho, n_real, rng_series)
    for row in full:
        key = row.tobytes()
        assert key not in seen, f"duplicate realization: {split}/{variant}/rho{rho}/c{c}/tau{tau_idx}"
        seen.add(key)
    shown = round2(full)

    rng_noise = rng_for("noise", variant, split, rho_idx, c_idx, tau_idx)
    u1, u2 = B.draw_correlated_noise(n_real, N_ROUNDS, tau1, tau2, c, rng_noise)

    stale_flags = None
    if variant == "stale":
        rng_flag = rng_for("stale_flag", variant, split, rho_idx, c_idx, tau_idx)
        stale_flags = rng_flag.random((n_real, N_ROUNDS)) < P_STALE
        stale_flags[:, 0] = False  # round 1 has no previous round to repeat

    rows = []
    for i in range(n_real):
        prev_s2 = None
        for r in range(1, N_ROUNDS + 1):
            t = round_index(r)
            hist = shown[i, t - HISTORY_LEN + 1: t + 1]
            x_t = float(shown[i, t])
            x_next = float(shown[i, t + 1])
            true_eps_next = float(round2(x_next - rho * x_t))

            s1_raw = true_eps_next + u1[i, r - 1]
            s2_honest_raw = true_eps_next + u2[i, r - 1]
            flip_applied = None
            if variant == "contradiction":
                flip_applied = bool(np.sign(s1_raw) == np.sign(s2_honest_raw))
                s2_raw = -s2_honest_raw if flip_applied else s2_honest_raw
            else:
                s2_raw = s2_honest_raw
            s1 = float(round2(s1_raw))
            s2 = float(round2(s2_raw))

            stale_round = False
            stale_source_round = None
            prev_note = None
            if variant == "stale":
                prev_note = prev_s2 if r >= 2 else None
                if r >= 2 and bool(stale_flags[i, r - 1]):
                    s2 = prev_s2
                    stale_round = True
                    stale_source_round = r - 1

            if stale_round:
                mean, var = B.one_signal(s1, tau1, SIGMA)
                w1, w2 = 1.0, 0.0
            elif variant == "contradiction":
                mean, var, w1, w2 = B.two_signal_general(s1, s2, tau1, tau2, c, SIGMA)
            else:
                mean, var, w1, w2 = B.two_signal_symmetric(s1, s2, tau1, c, SIGMA)

            bayes_delta1 = float(round2((rho - 1.0) * x_t + mean))
            bayes_var = float(round2(var))
            w1r, w2r = float(np.round(w1, WEIGHT_PREC)), float(np.round(w2, WEIGHT_PREC))

            prompt_variants = build_variants(hist, s1, s2, tau1, tau2, prev_s2=prev_note)
            sft = sft_target_text(tau1, tau2, stale_round, bayes_delta1)

            rows.append({
                "id": f"evid-{split}-{variant}-rho{rho:.1f}-c{c:.2f}-tau-{tau_setting}-real{i:03d}-round{r:02d}",
                "split": split, "variant": variant, "rho": float(rho), "c": float(c), "tau_setting": tau_setting,
                "tau1": float(tau1), "tau2": float(tau2), "tau": float(tau1), "realization": i, "round": r,
                "t_index": t, "history": [float(v) for v in hist], "x_t": x_t, "x_next": x_next,
                "true_eps_next": true_eps_next, "s1": s1, "s2": s2, "weight_s1": w1r, "weight_s2": w2r,
                "bayes_optimal_delta1": bayes_delta1, "bayes_optimal_posterior_var": bayes_var,
                "stale_round": stale_round, "stale_source_round": stale_source_round,
                "contradiction_flip_applied": flip_applied, "prompt_variants": prompt_variants, "sft_target": sft,
            })
            prev_s2 = s2
    return rows


def conditions():
    """Yields (variant, rho, rho_idx, c, c_idx, tau1, tau2, tau_idx, tau_setting) in fixed order: 18 base (3 rho
    x 3 c x 2 tau) + 6 stale (3 rho x 2 tau, c fixed 0.0) + 6 contradiction (3 rho x 2 precision regimes) = 30."""
    for rho_idx, rho in enumerate(RHOS):
        for c_idx, c in enumerate(C_VALUES):
            for tau_idx, (label, tau) in enumerate(TAU_SETTINGS.items()):
                yield "base", rho, rho_idx, c, c_idx, tau, tau, tau_idx, label
    for rho_idx, rho in enumerate(RHOS):
        for tau_idx, (label, tau) in enumerate(TAU_SETTINGS.items()):
            yield "stale", rho, rho_idx, 0.0, 0, tau, tau, tau_idx, label
    for rho_idx, rho in enumerate(RHOS):
        for tau_idx, (label, (tau1, tau2)) in enumerate(CONTRA_REGIMES.items()):
            yield "contradiction", rho, rho_idx, 0.0, 0, tau1, tau2, tau_idx, label


def self_checks(all_rows_by_split: dict) -> dict:
    """Lightweight, auditable build-time checks (DESIGN.md S7)."""
    out = {}
    by_cond = {}
    for rows in all_rows_by_split.values():
        for row in rows:
            if row["variant"] != "base":
                continue
            key = (row["rho"], row["c"], row["tau_setting"])
            by_cond.setdefault(key, set()).add(row["bayes_optimal_posterior_var"])
    out["base_posterior_var_constant_within_condition"] = all(len(v) == 1 for v in by_cond.values())
    out["base_weights_always_equal"] = all(
        row["weight_s1"] == row["weight_s2"]
        for rows in all_rows_by_split.values() for row in rows if row["variant"] == "base")
    tau_info, tau_noisy = TAU_SETTINGS["informative"], TAU_SETTINGS["noisy"]
    out["delta_var_c0_informative"] = float(B.delta_var_from_c(0.0, tau_info, SIGMA))
    out["delta_var_c0_noisy"] = float(B.delta_var_from_c(0.0, tau_noisy, SIGMA))
    out["delta_var_c_to_1_informative"] = float(B.delta_var_from_c(0.999999, tau_info, SIGMA))
    out["delta_var_is_zero_at_c1_exact"] = float(B.delta_var_from_c(1.0, tau_info, SIGMA))
    stale_rows = [row for rows in all_rows_by_split.values() for row in rows
                  if row["variant"] == "stale" and row["stale_round"]]
    out["n_stale_rounds"] = len(stale_rows)
    out["stale_weight_s2_always_zero"] = all(row["weight_s2"] == 0.0 for row in stale_rows)
    out["stale_var_matches_one_signal_formula"] = all(
        abs(row["bayes_optimal_posterior_var"] - float(round2(B.one_signal(row["s1"], row["tau1"], SIGMA)[1]))) < 1e-9
        for row in stale_rows)
    out["stale_s2_equals_prev_round_s2"] = True
    for rows in all_rows_by_split.values():
        by_real = {}
        for row in rows:
            if row["variant"] != "stale":
                continue
            by_real.setdefault((row["rho"], row["c"], row["tau_setting"], row["realization"]), {})[row["round"]] = row
        for d in by_real.values():
            for row in d.values():
                if row["stale_round"] and row["s2"] != d[row["stale_source_round"]]["s2"]:
                    out["stale_s2_equals_prev_round_s2"] = False
    contra_rows = [row for rows in all_rows_by_split.values() for row in rows if row["variant"] == "contradiction"]
    out["n_contradiction_rounds"] = len(contra_rows)
    out["contradiction_always_opposite_sign"] = all(
        np.sign(row["s1"]) != np.sign(row["s2"]) for row in contra_rows if row["s1"] != 0 and row["s2"] != 0)
    out["contradiction_flip_rate"] = float(np.mean([row["contradiction_flip_applied"] for row in contra_rows]))
    num_re = re.compile(r"Signal [AB]: (-?\d+\.?\d*) \(noise level: (-?\d+\.?\d*)\)")
    mismatches = 0
    for rows in all_rows_by_split.values():
        for row in rows:
            base_vals = sorted(num_re.findall(row["prompt_variants"]["base"]))
            swap_vals = sorted(num_re.findall(row["prompt_variants"]["position_swapped"]))
            mismatches += base_vals != swap_vals
    out["position_swap_information_equivalent"] = (mismatches == 0)
    return out


def build_rows() -> tuple[dict[str, list[dict]], int]:
    """({split: rows}, number of globally-unique AR(1) realizations) -- every row of every (variant, rho, c,
    tau) condition, in the fixed order of `conditions()`. One `seen` set is shared across every split and
    condition (DESIGN.md S2): `build_condition` asserts a realization is never generated twice, so a
    successful build's `len(seen)` is also a proof of zero collisions, not merely a count."""
    all_rows_by_split, seen = {}, set()
    for split in SPLITS:
        rows = []
        for variant, rho, rho_idx, c, c_idx, tau1, tau2, tau_idx, tau_setting in conditions():
            rows.extend(build_condition(split, variant, rho, rho_idx, c, c_idx, tau1, tau2, tau_idx, tau_setting, seen))
        all_rows_by_split[split] = rows
    return all_rows_by_split, len(seen)


def encode_jsonl(rows: list[dict]) -> bytes:
    return ("\n".join(json.dumps(row, ensure_ascii=False) for row in rows) + "\n").encode("utf-8")


XZ_FORMAT, XZ_CHECK, XZ_PRESET = lzma.FORMAT_XZ, lzma.CHECK_CRC64, 9  # fixed, so compression is byte-identical


def compress_xz(data: bytes) -> bytes:
    return lzma.compress(data, format=XZ_FORMAT, check=XZ_CHECK, preset=XZ_PRESET)


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def build(write_to: Path | None = None) -> tuple[dict[str, bytes], dict[str, bytes], dict]:
    """(jsonl bytes by split, .xz bytes by split, summary). If write_to is given, also writes
    `{split}.jsonl.xz`, `build_summary.json` and `MANIFEST.sha256` there. `summary` holds no wall-clock timing
    (that would make `build_summary.json`, and hence `MANIFEST.sha256`, differ between two deterministic runs
    for a reason that has nothing to do with the data; see DESIGN.md S8) -- time it from the outside if needed."""
    all_rows_by_split, n_unique_realizations = build_rows()
    checks = self_checks(all_rows_by_split)

    jsonl_bytes, xz_bytes, counts = {}, {}, {}
    for split in SPLITS:
        rows = all_rows_by_split[split]
        data = encode_jsonl(rows)
        jsonl_bytes[split] = data
        xz_bytes[split] = compress_xz(data)
        c = {}
        for row in rows:
            key = (row["variant"], f"{row['rho']:.1f}", f"{row['c']:.2f}", row["tau_setting"])
            cc = c.setdefault(key, {"realizations": set(), "rows": 0})
            cc["realizations"].add(row["realization"])
            cc["rows"] += 1
        counts[split] = {"|".join(k): {"realizations": len(v["realizations"]), "rows": v["rows"]}
                         for k, v in sorted(c.items())}

    total_rows = sum(len(v) for v in all_rows_by_split.values())
    summary = {
        "counts": counts, "total_rows": total_rows, "n_conditions": len(list(conditions())),
        "n_unique_realizations": n_unique_realizations,
        "decompressed_bytes": {f"{s}.jsonl": len(jsonl_bytes[s]) for s in SPLITS},
        "decompressed_sha256": {f"{s}.jsonl": sha256_bytes(jsonl_bytes[s]) for s in SPLITS},
        "compressed_bytes": {f"{s}.jsonl.xz": len(xz_bytes[s]) for s in SPLITS},
        "compressed_sha256": {f"{s}.jsonl.xz": sha256_bytes(xz_bytes[s]) for s in SPLITS},
        "xz_format": "FORMAT_XZ", "xz_check": "CHECK_CRC64", "xz_preset": XZ_PRESET,
        "checks": checks, "python": platform.python_version(), "numpy": np.__version__, "base_seed": BASE_SEED,
    }

    if write_to is not None:
        write_to.mkdir(parents=True, exist_ok=True)
        for split in SPLITS:
            (write_to / f"{split}.jsonl.xz").write_bytes(xz_bytes[split])
        (write_to / "build_summary.json").write_text(json.dumps(summary, indent=1) + "\n", encoding="utf-8")
        write_manifest(write_to)

    return jsonl_bytes, xz_bytes, summary


def write_manifest(out_dir: Path) -> None:
    """MANIFEST.sha256 of every file in out_dir except itself (DESIGN.md/README.md/build_summary.json included
    when already present), sorted by name -- a sha256sum-compatible manifest of the whole output folder."""
    names = sorted(p.name for p in out_dir.iterdir() if p.is_file() and p.name != "MANIFEST.sha256")
    with open(out_dir / "MANIFEST.sha256", "w", encoding="utf-8", newline="\n") as f:
        for name in names:
            f.write(f"{sha256_file(out_dir / name)}  {name}\n")


# ================================================================================================== CLI
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="finagent evidence-synthetic", description="Regenerate "
                                 "data/evidence_relations/synthetic/{train,val,test}.jsonl.xz + MANIFEST.sha256 from the "
                                 "generator, or --check them against the shipped archive (both must agree).")
    ap.add_argument("--out", type=Path, default=EVIDENCE_ROOT / "synthetic",
                    help="target folder (default: data/evidence_relations/synthetic/)")
    ap.add_argument("--check", action="store_true",
                    help="write nothing; regenerate in memory and compare with --out's shipped .xz files and manifest")
    a = ap.parse_args(argv)

    if not a.check:
        _, _, summary = build(write_to=a.out)
        print(json.dumps(summary, indent=1))
        print(f"wrote {len(SPLITS)} .xz files + build_summary.json + MANIFEST.sha256 to {a.out}")
        return 0

    jsonl_bytes, xz_bytes, summary = build(write_to=None)
    bad = []
    for split in SPLITS:
        shipped_path = a.out / f"{split}.jsonl.xz"
        if not shipped_path.is_file():
            bad.append(f"{split}.jsonl.xz: missing")
            continue
        shipped_xz = shipped_path.read_bytes()
        shipped_decompressed = lzma.decompress(shipped_xz)
        if shipped_decompressed != jsonl_bytes[split]:
            bad.append(f"{split}.jsonl.xz: decompressed content differs from a fresh regeneration")
        elif shipped_xz != xz_bytes[split]:
            bad.append(f"{split}.jsonl.xz: same decompressed content, but compressed bytes differ "
                       "(xz settings drifted)")
    want_summary_path = a.out / "build_summary.json"
    if want_summary_path.is_file():
        want = json.loads(want_summary_path.read_text(encoding="utf-8"))
        for key in ("total_rows", "n_conditions", "n_unique_realizations", "checks", "decompressed_sha256",
                    "compressed_sha256"):
            if want.get(key) != summary.get(key):
                bad.append(f"build_summary.json[{key}]: differs from a fresh regeneration")
    else:
        bad.append("build_summary.json: missing")
    n = len(SPLITS) + 1
    print(f"{n - len(bad)} of {n} shipped files match a fresh regeneration of {a.out}"
          + "".join(f"\n  DIFFERS: {b}" for b in bad))
    return 1 if bad else 0


