import argparse
import hashlib
import json
from pathlib import Path

from finagent.evidence_relations.tool_redundancy import analyze as A
from finagent.evidence_relations.tool_redundancy import generate as G
from finagent.evidence_relations.tool_redundancy.generate import EXCLUDED_TOOLS, INCLUDED_TOOLS, OUT_DIR

