"""tool_redundancy: an empirical tool-redundancy matrix for the 31 non-submit toolbox tools, over all 96
data/pit_cache tickers. generate.py pulls the raw (ticker, day, tool, field) features through finagent's own
toolbox; analyze.py turns them into the correlation matrix and summary tables. CPU only, no GPU, no model calls.

    finagent evidence-tools                    generate (default --workers 32) then analyze, then write
                                                 README.md and MANIFEST.sha256
    finagent evidence-tools --workers N --out DIR

Ported from 1_overreaction/repro/evidence_relations/tool_redundancy_{generate,analyze}.py; see
tool_redundancy/README.md for the full design and a source-vs-port comparison of every count.
"""
