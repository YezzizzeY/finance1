def write_outputs(out_dir: Path) -> dict:
    meta_g = json.loads((out_dir / "_generate_meta.json").read_text())
    meta_a = json.loads((out_dir / "_analyze_meta.json").read_text())

    import csv
    clusters = list(csv.DictReader(open(out_dir / "clusters.csv")))
    clusters.sort(key=lambda r: -int(r["size"]))
    c0 = clusters[0]
    c0_tools = sorted({m.split(".", 1)[0] for m in c0["members"].split(";")})

    fmt = dict(
        n_tickers=meta_g["n_tickers"], n_rows=meta_a["n_rows"], n_included=len(INCLUDED_TOOLS),
        n_numeric_cols_total=meta_a["n_numeric_cols_total"], n_cols_kept=meta_a["n_cols_kept"],
        n_cols_dropped=meta_a["n_cols_dropped"], n_pairs_total=meta_a["n_pairs_total"],
        n_pairs_cross_tool=meta_a["n_pairs_cross_tool_with_min_n"], n_tool_pairs=meta_a["n_tool_pairs"],
        n_redundant=meta_a["n_tool_pairs_fully_redundant"], n_independent=meta_a["n_tool_pairs_fully_independent"],
        n_mixed=meta_a["n_tool_pairs_mixed"], n_near_independent=meta_a["n_near_independent"],
        n_clusters=meta_a["n_clusters_ge2"], n_edges=meta_a["cluster_edge_count_ge_0_9"],
        excluded=", ".join(sorted(EXCLUDED_TOOLS)), included=", ".join(INCLUDED_TOOLS),
        cluster0_size=c0["size"], cluster0_n_tools=len(c0_tools), cluster0_tools_list=", ".join(c0_tools),
        cluster0_tools="`" + "`, `".join(sorted(c0["members"].split(";"))) + "`",
        min_n=A.MIN_N_FOR_SUMMARY,
    )
    (out_dir / "README.md").write_text(TOP_README.format(**fmt))

    manifest_lines = []
    for p in sorted(out_dir.rglob("*")):
        if p.is_file() and p.name not in ("MANIFEST.sha256", "README.md") and not p.name.startswith("."):
            manifest_lines.append(f"{hashlib.sha256(p.read_bytes()).hexdigest()}  ./{p.relative_to(out_dir).as_posix()}")
    manifest_lines.append(f"{hashlib.sha256((out_dir / 'README.md').read_bytes()).hexdigest()}  ./README.md")
    manifest_lines.sort(key=lambda ln: ln.split("  ", 1)[1])
    (out_dir / "MANIFEST.sha256").write_text("\n".join(manifest_lines) + "\n")
    return fmt


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="finagent evidence-tools", description="Generate + analyze the tool-redundancy matrix.")
    ap.add_argument("--workers", type=int, default=32)
    ap.add_argument("--out", type=Path, default=OUT_DIR)
    ap.add_argument("--skip-generate", action="store_true", help="reuse an existing raw_features.parquet")
    a = ap.parse_args(argv)
    if not a.skip_generate:
        G.main(["--workers", str(a.workers), "--out", str(a.out)])
    A.main(["--out", str(a.out)])
    fmt = write_outputs(a.out)
    print(json.dumps(fmt, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
